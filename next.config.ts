import type { NextConfig } from "next";

// Report-only for now: violations are posted to /api/csp-report (Vercel function
// logs) and nothing is blocked. Once the logs stay empty, rename the header to
// Content-Security-Policy. Inline scripts are Next's own bootstrap and the JSON-LD.
const csp = [
  "default-src 'self'",
  "script-src 'self' 'unsafe-inline'",
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data: blob:",
  "font-src 'self'",
  "media-src 'self'",
  "connect-src 'self'",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "frame-ancestors 'none'",
  "report-uri /api/csp-report",
  "report-to csp",
].join("; ");

const nextConfig: NextConfig = {
  poweredByHeader: false,
  turbopack: {
    root: process.cwd(),
  },
  async headers() {
    return [
      {
        source: "/(.*)",
        headers: [
          {
            key: "Strict-Transport-Security",
            value: "max-age=63072000; includeSubDomains; preload",
          },
          { key: "X-Content-Type-Options", value: "nosniff" },
          {
            key: "Referrer-Policy",
            value: "strict-origin-when-cross-origin",
          },
          {
            key: "Permissions-Policy",
            value: "camera=(), microphone=(), geolocation=()",
          },
          { key: "X-Frame-Options", value: "DENY" },
          { key: "Reporting-Endpoints", value: 'csp="/api/csp-report"' },
          { key: "Content-Security-Policy-Report-Only", value: csp },
        ],
      },
      {
        // Vercel serves public/ with max-age=0, so every repeat visit
        // revalidated each clip. The names are not hashed (a new take keeps
        // its name), so cache for a day and refresh in the background after.
        source: "/videos/:path*",
        headers: [
          {
            key: "Cache-Control",
            value: "public, max-age=86400, stale-while-revalidate=604800",
          },
        ],
      },
    ];
  },
};

export default nextConfig;
