import type { Metadata, ResolvingMetadata } from "next";
import { SITE_NAME } from "@/data/site";

/** Same suffix as the layout's title template ("%s · Zuemen Chu"). */
const TITLE_SUFFIX = " · Zuemen Chu";

/**
 * generateMetadata for a subpage: its own canonical, og:url and og/twitter
 * title. Without this every page declared the homepage as its canonical, so
 * search engines could treat subpages as duplicates of it.
 *
 * Next merges metadata shallowly — a page that sets `openGraph` or `twitter`
 * replaces the layout's whole object — so siteName, locale and type are
 * repeated here, and the share image generated by app/opengraph-image.tsx is
 * carried over from the parent rather than hard-coding its hashed URL.
 * Paths are resolved against the layout's metadataBase.
 */
export const pageMetadata =
  ({
    path,
    title,
    description,
  }: {
    path: string;
    title: string;
    description: string;
  }) =>
  async (_props: unknown, parent: ResolvingMetadata): Promise<Metadata> => {
    const inherited = await parent;
    const fullTitle = `${title}${TITLE_SUFFIX}`;
    return {
      title,
      description,
      alternates: { canonical: path },
      openGraph: {
        type: "profile",
        url: path,
        title: fullTitle,
        description,
        siteName: SITE_NAME,
        locale: "en_US",
        images: inherited.openGraph?.images,
      },
      twitter: {
        card: "summary_large_image",
        title: fullTitle,
        description,
        images: inherited.twitter?.images,
      },
    };
  };
